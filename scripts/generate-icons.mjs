// Generates src/components/icons.generated.ts: the bold outline of each icon the app uses, taken from
// @phosphor-icons/react (MIT licence). The package ships every icon in six weights (about 115 kB in the bundle);
// the app only ever draws the bold one. Run after adding an icon:  node scripts/generate-icons.mjs
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ICONS = { home: "House", book: "BookOpen", check: "CheckCircle", exam: "Trophy", trophy: "Trophy", more: "List", sign: "Warning", chart: "ChartBar", words: "Translate",
  bookmark: "BookmarkSimple", pin: "MapPin", user: "UserCircle", lock: "Lock", gear: "Gear", info: "Info", flame: "Flame", target: "Target", star: "Star", arrow: "ArrowRight",
  sparkle: "Sparkle", bell: "Bell", calendar: "CalendarCheck", car: "Car", play: "Play", wifi: "WifiHigh", shield: "ShieldCheck", devices: "Devices", close: "X",
  download: "DownloadSimple", signout: "SignOut", trash: "Trash", cloudUp: "CloudArrowUp", cloudDown: "CloudArrowDown", globe: "Globe", verified: "SealCheck", alert: "WarningCircle",
  zoomIn: "MagnifyingGlassPlus", zoomOut: "MagnifyingGlassMinus", fullscreen: "CornersOut", replay: "ArrowCounterClockwise" };
const extra = process.argv.slice(2);
for (const pair of extra) { const [k, v] = pair.split("="); ICONS[k] = v; }

const out = {};
for (const [name, component] of Object.entries(ICONS)) {
  const defs = (await import(pathToFileURL(resolve(`node_modules/@phosphor-icons/react/dist/defs/${component}.es.js`)).href)).default;
  const bold = defs.get("bold");
  const paths = [];
  const walk = (el) => {
    if (!el) return;
    if (Array.isArray(el)) return el.forEach(walk);
    if (el.type === "path") { if (Object.keys(el.props).some((k) => k !== "d")) throw new Error(`${component}: unsupported path attribute`); paths.push(el.props.d); }
    else if (typeof el.type === "symbol" || el.type === undefined) walk(el.props?.children);
    else throw new Error(`${component}: unsupported element <${String(el.type)}>`);
  };
  walk(bold);
  if (!paths.length) throw new Error(`${component}: no bold outline`);
  out[name] = paths;
}
writeFileSync("src/components/icons.generated.ts",
  `// GENERATED by scripts/generate-icons.mjs — do not edit. Bold outlines from @phosphor-icons/react (MIT licence,\n// Copyright (c) Phosphor Icons). viewBox 0 0 256 256.\nexport const ICON_PATHS = ${JSON.stringify(out, null, 1)} as const;\n`);
console.log(`icons: ${Object.keys(out).length}, ${JSON.stringify(out).length} bytes`);
